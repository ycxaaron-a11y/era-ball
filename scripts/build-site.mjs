import {createHash} from 'node:crypto';
import {readdirSync,readFileSync,writeFileSync,mkdirSync,cpSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const files=readdirSync(root).filter(name=>/\.(js|css)$/.test(name)).sort();
const source=readFileSync(join(root,'index.html'),'utf8');
const hash=createHash('sha256').update(source);
for(const name of files)hash.update(name).update(readFileSync(join(root,name)));
hash.update(readFileSync(join(root,'assets/walnut.svg')));
const release=hash.digest('hex').slice(0,12),out=join(root,'dist'),folder=join(out,'releases',release);
mkdirSync(folder,{recursive:true});
for(const name of files)writeFileSync(join(folder,name),readFileSync(join(root,name)));
cpSync(join(root,'assets'),join(folder,'assets'),{recursive:true});
cpSync(join(root,'docs'),join(out,'docs'),{recursive:true});
mkdirSync(join(out,'supabase'),{recursive:true});
writeFileSync(join(out,'supabase/setup-all.sql'),readFileSync(join(root,'supabase/setup-all.sql')));
const html=source.replace(/(href|src)="(style\.css|atelier\.css|app\.js)"/g,(_,attr,file)=>`${attr}="releases/${release}/${file}"`).replace('星尘版 · R13',`星尘版 · R13 · ${release.slice(0,7)}`);
writeFileSync(join(out,'index.html'),html);
writeFileSync(join(out,'release.json'),JSON.stringify({release,label:'星尘版 R13'},null,2)+'\n');
console.log(`Built 星尘版 R13 ${release}: ${files.length} versioned JS/CSS files, docs and upgrade SQL.`);
